/**
 * Resolves achievement metadata from either a string key or an object payload.
 * Preserves existing definitions without inventing unauthorized metrics.
 */
export function resolveAchievementMeta(item) {
  if (!item) {
    return {
      id: "unknown",
      title: "Achievement",
      desc: "Platform achievement unlocked.",
      iconName: "Award",
    };
  }

  if (typeof item === "object") {
    const rawKey = item.id || item.key || item.title || "";
    const base =
      ACHIEVEMENT_METADATA[rawKey] ||
      ACHIEVEMENT_METADATA[String(rawKey).toLowerCase().replaceAll(" ", "_")] ||
      {};

    return {
      id: rawKey || "achievement",
      title:
        item.title ||
        base.title ||
        String(rawKey).replaceAll("_", " ").replace(/\b\w/g, (l) => l.toUpperCase()),
      desc: item.desc || item.description || base.desc || "Platform achievement unlocked.",
      iconName: item.iconName || (typeof item.icon === "string" ? item.icon : null) || base.iconName || "Award",
      iconComponent: typeof item.icon === "function" || (item.icon && typeof item.icon === "object") ? item.icon : null,
      category: item.category || base.category,
      xp: item.xp || item.points,
      date: item.earnedAt || item.unlockedAt || item.date,
    };
  }

  const key = String(item).trim();
  if (ACHIEVEMENT_METADATA[key]) {
    return {
      id: key,
      ...ACHIEVEMENT_METADATA[key],
    };
  }

  const normalized = key.toLowerCase().replaceAll(" ", "_");
  if (ACHIEVEMENT_METADATA[normalized]) {
    return {
      id: key,
      ...ACHIEVEMENT_METADATA[normalized],
    };
  }

  return {
    id: key,
    title: key.replaceAll("_", " ").replace(/\b\w/g, (l) => l.toUpperCase()),
    desc: "Platform achievement unlocked.",
    iconName: "Award",
  };
}
